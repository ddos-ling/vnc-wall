_SHIFTS = (1, 1, 2, 2, 2, 2, 2, 2, 1, 2, 2, 2, 2, 2, 2, 1)


def _permute(value: int, table: tuple[int, ...], in_bits: int) -> int:
    """按 DES 置换表重排比特,table 中 1 表示最高位"""
    out = 0
    for pos in table:
        out = (out << 1) | ((value >> (in_bits - pos)) & 1)
    return out


def _f(right: int, subkey: int) -> int:
    x = _permute(right, _E, 32) ^ subkey
    out = 0
    for i in range(8):
        chunk = (x >> (42 - 6 * i)) & 0x3F
        row = ((chunk >> 4) & 0x2) | (chunk & 0x1)
        col = (chunk >> 1) & 0xF
        out = (out << 4) | _SBOX[i][row * 16 + col]
    return _permute(out, _P, 32)


def _subkeys(key: bytes) -> list[int]:
    k = int.from_bytes(key, "big")
    cd = _permute(k, _PC1, 64)
    c = (cd >> 28) & 0x0FFFFFFF
    d = cd & 0x0FFFFFFF
    keys = []
    for shift in _SHIFTS:
        c = ((c << shift) | (c >> (28 - shift))) & 0x0FFFFFFF
        d = ((d << shift) | (d >> (28 - shift))) & 0x0FFFFFFF
        keys.append(_permute((c << 28) | d, _PC2, 56))
    return keys


def encrypt_block(key: bytes, block: bytes) -> bytes:
    """标准 DES ECB 单块加密(key 8 字节,block 8 字节)"""
    if len(key) != 8 or len(block) != 8:
        raise ValueError("key 与 block 必须为 8 字节")
    ks = _subkeys(key)
    m = _permute(int.from_bytes(block, "big"), _IP, 64)
    left = (m >> 32) & 0xFFFFFFFF
    right = m & 0xFFFFFFFF
    for subkey in ks:
        left, right = right, left ^ _f(right, subkey)
    return _permute((right << 32) | left, _FP, 64).to_bytes(8, "big")


_BIT_REVERSE = bytes(int(f"{i:08b}"[::-1], 2) for i in range(256))


def vnc_response(password: str, challenge: bytes) -> bytes:
    """按 VNC 规则用密码加密 16 字节 challenge

    注意:VNC 使用的密钥是密码字节逐位反转后的结果,这是原始 AT&T VNC
    实现留下来并已被所有服务端沿用的约定,不加这步会一直密码错误
    """
    if len(challenge) != 16:
        raise ValueError("challenge 必须为 16 字节")
    raw = password.encode("latin-1", "replace")[:8]
    key = (raw + b"\x00" * 8)[:8]
    key = bytes(_BIT_REVERSE[b] for b in key)
    return encrypt_block(key, challenge[:8]) + encrypt_block(key, challenge[8:])
